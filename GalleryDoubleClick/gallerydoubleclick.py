def _on_toggled(button):
    CONFIG.set("behavior.use-system-viewer", button.get_active())
    CONFIG.save()


def _add_checkbox(widget):
    """
    Build the checkbox and insert it below the last existing checkbox of the
    given tab widget (or at the bottom if there is none). Return True if done.
    """
    check = Gtk.CheckButton(
        label=_(
            "Double-clicking media in a Gallery tab opens the "
            "system default viewer"
        )
    )
    check.set_tooltip_text(
        _(
            "Unchecked: opens the Media Reference Editor.\n"
            "Checked: opens the file in the system default application."
        )
    )
    check.set_active(use_system_viewer())
    check.connect("toggled", _on_toggled)

    # Unwrap scrolled windows / viewports if present
    while isinstance(widget, (Gtk.ScrolledWindow, Gtk.Viewport)):
        widget = widget.get_child()

    if isinstance(widget, Gtk.Grid):
        # Place the option directly below the last existing checkbox, in the
        # same column, pushing the rows below it (entries, notes) down.
        last_check = None
        last_top = -1
        bottom = 0
        for child in widget.get_children():
            top = widget.child_get_property(child, "top-attach")
            height = widget.child_get_property(child, "height")
            bottom = max(bottom, top + height)
            if isinstance(child, Gtk.CheckButton) and top > last_top:
                last_check, last_top = child, top
        if last_check is not None:
            left = widget.child_get_property(last_check, "left-attach")
            width = widget.child_get_property(last_check, "width")
            row = last_top + widget.child_get_property(last_check, "height")
            widget.insert_row(row)
            widget.attach(check, left, row, width, 1)
        else:
            widget.attach(check, 1, bottom, 8, 1)
    elif isinstance(widget, Gtk.Box):
        widget.pack_start(check, False, False, 6)
    else:
        return False
    check.show()
    return True


