CONFIG = config.register_manager("gallerydoubleclick")
CONFIG.register("behavior.use-system-viewer", False)
CONFIG.init()

# Marker set on our wrapper functions so they are never installed twice
_MARK = "_gallerydoubleclick_patched"


def use_system_viewer():
    """Return True if gallery double-click should use the system viewer."""
    return bool(CONFIG.get("behavior.use-system-viewer"))


# -------------------------------------------------------------------------
# Part 1: gallery double-click
# -------------------------------------------------------------------------
def _view_selected(tab):
    """
    Hand the selected media to the system viewer. Return True if the request
    was made (the helper reports its own launch errors), False if there was
    nothing usable to open, so the caller can fall back to the stock handler.
    """
    try:
        ref = tab.get_selected()
        if ref is None:
            return False
        db = tab.dbstate.db
        media = db.get_media_from_handle(ref.get_reference_handle())
        if media is None or not media.get_path():
            return False
        path = media_path_full(db, media.get_path())
        open_file_with_default_application(path, tab.uistate)
        return True
    except Exception:  # pylint: disable=broad-except
        LOG.exception("Could not open media in system viewer")
        return False


def _patch_gallery_tab():
    """
    Wrap GalleryTab.double_click. Left-button double clicks are redirected to
    the system viewer when the option is on; everything else (right-click
    menu, single clicks) goes to the original handler untouched.
    """
    original = GalleryTab.double_click
    if getattr(original, _MARK, False):
        return

    def double_click(self, obj, event):
        if (
            use_system_viewer()
            and event.type == Gdk.EventType.DOUBLE_BUTTON_PRESS
            and event.button == 1
        ):
            if _view_selected(self):
                return True
        return original(self, obj, event)

    setattr(double_click, _MARK, True)
    GalleryTab.double_click = double_click


